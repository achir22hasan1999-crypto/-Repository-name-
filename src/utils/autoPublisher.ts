export function getAutoPublishLogs(): AutoPublishLog[] {
  try {
    const raw = localStorage.getItem(AUTOPUBLISH_LOGS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {
    console.error('Error reading auto-publish logs:', e);
  }
  return DEFAULT_SEEDED_LOGS;
}

export function saveAutoPublishLogs(logs: AutoPublishLog[]): void {
  try {
    // Keep last 100 logs
    const trimmed = logs.slice(0, 100);
    localStorage.setItem(AUTOPUBLISH_LOGS_KEY, JSON.stringify(trimmed));
  } catch (e) {
    console.error('Error saving auto-publish logs:', e);
  }
}

export function addAutoPublishLog(log: Omit<AutoPublishLog, 'id'>): void {
  const logs = getAutoPublishLogs();
  const newLog: AutoPublishLog = {
    id: `log-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
    ...log,
  };
  saveAutoPublishLogs([newLog, ...logs]);
}

